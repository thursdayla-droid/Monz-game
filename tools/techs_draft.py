# ---- BUNK(今のゲームの表。くらべるため) ----
def load_bunk():
    rows = []
    with open(os.path.join(root, 'data', 'monz_techs.csv'), encoding='utf-8-sig') as f:
        for r in csv.DictReader(f):
            rows.append((int(r['覚えるレベル']), r['条件'], r['技名'], r['型'], r['属性'], r['強さ'], r['追加効果'], r['見た目のメモ']))
    return rows


def calc(typ, st):
    """型と強さから、技の数字(BUNK と同じ決め方)。火柱(BUNK のレンゴクホウケン)は ゲームの数字を使う"""
    if typ == '火柱':
        return dict(power=21.6, cd=8.1, windup=0.58, range=14, size=1.15, dur=0.4, hits=1, label='21.6')
    b = BASE[typ]
    m = MUL[st]
    power = b['power'] * m['power']
    if typ == '設置' and b['power'] == 0:
        power = 0
    d = dict(
        power=power,
        cd=b['cd'] * m['cd'],
        windup=b['windup'] * m['windup'],
        range=b['range'] * (m['area'] if typ in AREA_RANGE else 1),
        size=b['size'] * (m['area'] if typ in AREA_SIZE else 1),
        dur=b['dur'] * (m['area'] if typ == '守り' else 1),
        hits=HITS[st] if typ == '連続攻撃' else 3 if typ == '連射' else 1,
    )
    if typ == '回復':
        d['label'] = f'HP{power:.0f}%回復'
    elif typ == '強化':
        d['label'] = f'+{power:.0f}%・{d["dur"]:.0f}秒'
    elif typ == '吸収':
        d['label'] = f'{power:.1f}(半分回復)'
    elif typ == '連射':
        d['label'] = f'{power:.2f}×3発'
    elif typ in ('守り', '弱体') or power == 0:
        d['label'] = '0'
    else:
        d['label'] = f'{power:.1f}'
    return d


def dmg_total(typ, d):
    """当たったときの合計ダメージの目安(回復・強化・守り・弱体は 0)"""
    if typ in ('回復', '強化', '守り', '弱体'):
        return 0
    return d['power'] * (3 if typ == '連射' else 1)


def range_text(typ, d):
    if typ in ('回復', '強化'):
        return '自分'
    if typ == '守り':
        return f'自分のまわり 半径{d["size"]:.1f}'
    if typ == '突進':
        return f'走る長さ {d["range"]:.0f}'
    if typ == '回転':
        return f'回って進む {d["range"]:.0f}'
    if typ in ('弾', '連射'):
        return '画面の端まで飛ぶ'
    if typ == 'ビーム':
        return f'長さ {d["range"]:.0f}'
    if typ == '衝撃波':
        return f'半径 {d["range"]:.1f} まで広がる'
    if typ == '落下':
        return f'跳べる長さ {d["range"]:.0f}'
    if typ == '連続攻撃':
        return f'近づく {d["range"]:.0f}'
    if typ == '弱体':
        return f'半径 {d["range"]:.0f} の声の輪'
    if typ == '設置':
        return '相手の足もと'
    if typ == '吸収':
        return f'{d["range"]:.0f} まで'
    if typ == '火柱':
        return '相手の足もと＋まわり3か所'
    return ''


def area_text(typ, d):
    if typ in ('弾', '連射', 'ビーム'):
        return f'太さ {d["size"]:.2f}'
    if typ == '落下':
        return f'落ちる円 半径{d["size"]:.1f}'
    if typ == '設置':
        return f'円 半径{d["size"]:.1f}'
    if typ == '守り':
        return f'ドーム 半径{d["size"]:.1f}'
    if typ == '火柱':
        return '柱 4本(太さ 1.15)'
    return '体の大きさ' if typ in ('突進', '回転', '連続攻撃', '吸収') else '―'


def dur_text(typ, d):
    if typ == '守り':
        return f'{d["dur"]:.1f}秒'
    if typ in ('弱体', '設置'):
        return f'{d["dur"]:.0f}秒'
    if typ == '強化':
        return f'{d["dur"]:.0f}秒'
    if typ == '回復':
        return f'{d["dur"]:.1f}秒 動けない'
    if typ == 'ビーム':
        return f'{d["dur"]:.1f}秒 出つづける'
    if typ == '回転':
        return f'{d["dur"]:.1f}秒'
    return '―'


def main():
    out_rows, det_rows = [], []
    for sp, (style, rows) in SPECIES.items():
        assert len(rows) == 17, sp
        for (lv, cond, name, typ, el, st, eff, memo) in rows:
            d = calc(typ, st)
            out_rows.append([sp, name, typ, el, st, lv, cond, eff, d['label'], f'{d["cd"]:.1f}', memo])
            det_rows.append([sp, name, typ, st, range_text(typ, d), area_text(typ, d), f'{d["windup"]:.2f}秒', dur_text(typ, d), d['hits'], f'{d["cd"]:.1f}秒'])
    with open(os.path.join(root, 'data', 'monz_techs_draft.csv'), 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(['種族', '技名', '型', '属性', '強さ', '覚えるレベル', '条件', '追加効果', '威力', '待ち時間', '見た目のメモ'])
        w.writerows(out_rows)
    with open(os.path.join(root, 'data', 'monz_techs_draft_detail.csv'), 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(['種族', '技名', '型', '強さ', '射程', '範囲', 'ため(出るまで)', '続く時間', '当たる数', '待ち時間'])
        w.writerows(det_rows)

    # ---- 種族の比べ ----
    allsp = {'BUNK': ('力・体当たり(今のゲーム)', load_bunk()), **SPECIES}
    lines = ['| 種族 | 攻撃の技 | 遠くから | 守り・回復・吸収 | 強化・弱体・設置 | 状態異常つき | 型と追加効果が今あるもの | Lv.1 の強さ※ | Lv.30 | Lv.60 | Lv.70 |', '|---|---|---|---|---|---|---|---|---|---|---|']
    for sp, (style, rows) in allsp.items():
        atk = [r for r in rows if r[3] not in ('回復', '強化', '守り', '弱体')]
        far = [r for r in rows if r[3] in ('弾', '連射', 'ビーム', '設置', '火柱')]
        dfn = [r for r in rows if r[3] in ('守り', '回復', '吸収')]
        sup = [r for r in rows if r[3] in ('強化', '弱体', '設置')]
        stt = [r for r in rows if r[6] != 'なし']
        # 今のゲームで動く: 型があり、追加効果が なし・ふらつき・まひ・攻撃ダウン・遅くする
        now = [r for r in rows if r[3] not in ('回復', '強化', '吸収') and r[6] in ('なし', 'ふらつき', 'まひ', '攻撃ダウン', '遅くする')]

        def dps(lv):
            # その レベルまでに覚える攻撃の技(Lv.25 の4つは のぞく)のうち、威力÷待ち時間 が大きい4つの平均
            xs = []
            for r in rows:
                if r[0] > lv or r[1] in (P, T, S, X):
                    continue
                d = calc(r[3], r[5])
                v = dmg_total(r[3], d)
                if v:
                    xs.append(v / d['cd'])
            xs.sort(reverse=True)
            xs = xs[:4]
            return sum(xs) / len(xs) if xs else 0
        lines.append(f'| {sp} | {len(atk)} | {len(far)} | {len(dfn)} | {len(sup)} | {len(stt)} | {len(now)}/17 | {dps(1):.2f} | {dps(30):.2f} | {dps(60):.2f} | {dps(70):.2f} |')

    # ---- 重なりの検出 ----
    dup = []
    for sp, (style, rows) in SPECIES.items():
        c = Counter(r[3] for r in rows)
        many = [f'{t}×{n}' for t, n in c.items() if n >= 3]
        if many:
            dup.append(f'- **{sp}**：同じ型が多い … {"・".join(many)}')
        same = defaultdict(list)
        for r in rows:
            same[(r[3], r[4], r[5])].append(r[2])
        for k, v in same.items():
            if len(v) >= 2:
                dup.append(f'- **{sp}**：型・属性・強さが同じ（{k[0]}・{k[1]}・{k[2]}）… {"／".join(v)}')
        eff = defaultdict(list)
        for r in rows:
            if r[3] == '弱体':
                eff[r[6]].append(r[2])
        for k, v in eff.items():
            if len(v) >= 2:
                dup.append(f'- **{sp}**：弱体の効果が同じ（{k}）… {"／".join(v)}')
    lv70 = Counter(rows[-1][3] for sp, (s, rows) in SPECIES.items())
    lv70txt = '・'.join(f'{t}×{n}' for t, n in lv70.most_common())
    types = Counter(r[3] for sp, (s, rows) in SPECIES.items() for r in rows)
    efx = Counter(r[6] for sp, (s, rows) in SPECIES.items() for r in rows)
    with open(os.path.join(root, 'docs', 'techs_draft_tables.md'), 'w', encoding='utf-8') as f:
        f.write('<!-- tools/techs_draft.py で作る。手で直さない -->\n\n')
        f.write('## 種族の比べ（自動計算）\n\n' + '\n'.join(lines) + '\n\n')
        f.write('※ 強さ = その時に覚えている攻撃の技（Lv.25 の4つはのぞく）のうち「当たった時のダメージ ÷ 待ち時間」が大きい4つの平均。当たりやすさ・相手の守り・回復は入っていない目安。\n\n')
        f.write('## 重なりの検出（自動）\n\n' + '\n'.join(dup) + f'\n- Lv.70 の型：{lv70txt}\n\n')
        f.write('## 153技の型の数\n\n' + '・'.join(f'{t} {n}' for t, n in types.most_common()) + '\n\n')
        f.write('## 追加効果の数\n\n' + '・'.join(f'{t} {n}' for t, n in efx.most_common()) + '\n')
    print(len(out_rows), 'rows')


if __name__ == '__main__':
    main()
