/** バトルモードの相手(CPUの強さごとに1人。企画者「良い」2026-10-27) */
const BATTLE_OPPONENTS: Record<CpuLevel, [string, string, string]> = {
  weak: ['ポポ', '見習いカード使い', 'お手やわらかにね！'],
  normal: ['レイン', '腕利きのカード使い', 'いい勝負にしよう'],
  strong: ['ゼクス', '最強のカード使い', '本気で かかってこい'],
};

const make = (id: string, [name, title, line]: [string, string, string]): Opponent => ({ id, name, title, line });

export const towerOpponent = (floor: number, battle: number): Opponent => make(`t${floor}-${battle + 1}`, TOWER_OPPONENTS[floor - 1][battle]);
export const battleOpponent = (level: CpuLevel): Opponent => make(`b-${level}`, BATTLE_OPPONENTS[level]);
export const opponentFor = (m: MythMatch): Opponent => (m.mode === 'tower' ? towerOpponent(m.floor, m.battle) : battleOpponent(m.level));

/** 全員(テスト・絵の用意のため) */
export const ALL_OPPONENTS: Opponent[] = [
  ...TOWER_OPPONENTS.flatMap((f, i) => f.map((_, b) => towerOpponent(i + 1, b))),
  ...(['weak', 'normal', 'strong'] as CpuLevel[]).map(battleOpponent),
];
